function addToCart(id) {
  cart[id] = (cart[id] || 0) + 1;
  saveAllState();
  updateCartUI();
}

function changeItemQty(id, delta) {
  if (!cart[id]) return;
  cart[id] += delta;
  if (cart[id] <= 0) {
    delete cart[id];
  }
  saveAllState();
  updateCartUI();
}

function updatePaymentView(method) {
  const qrBox = document.getElementById('promptPayBox');
  qrBox.style.display = method === 'promptpay' ? 'block' : 'none';
}

function calculateCartTotals() {
  const entries = Object.entries(cart);
  let subtotal = 0;
  let totalItems = 0;

  entries.forEach(([id, qty]) => {
    const item = TOY_TIMELINE.find((t) => t.id === id);
    if (item) {
      subtotal += item.price * qty;
      totalItems += qty;
    }
  });

  const stampDiscount = collectedStamps.length === TOY_TIMELINE.length && subtotal > 0 ? 50 : 0;
  const luckyDiscount = activeCoupon && subtotal > 0 ? activeCoupon.discount : 0;
  const finalTotal = Math.max(0, subtotal - stampDiscount - luckyDiscount);

  return { entries, subtotal, totalItems, stampDiscount, luckyDiscount, finalTotal };
}

function updateCartUI() {
  const { entries, subtotal, totalItems, stampDiscount, luckyDiscount, finalTotal } = calculateCartTotals();
  document.getElementById('cartBadgeCount').textContent = totalItems;

  const listEl = document.getElementById('cartItemsContainer');
  if (entries.length === 0) {
    listEl.innerHTML = `
      <div style="text-align: center; padding: 1.75rem 1rem; border: 2px dashed var(--border-ink); color: var(--text-secondary);">
        ยังไม่มีของเล่นในตะกร้า<br/>กดเลือกจากสมุดสติ๊กเกอร์ พ.ศ. 2533–2542 ได้เลยครับ!
      </div>
    `;
  } else {
    listEl.innerHTML = entries
      .map(([id, qty]) => {
        const item = TOY_TIMELINE.find((t) => t.id === id);
        if (!item) return '';
        return `
        <div class="cart-item">
          <div>
            <div style="font-family: 'Chakra Petch', sans-serif; font-weight: 700; font-size: 0.92rem;">
              ${item.name}
            </div>
            <div style="font-family: 'Space Mono', monospace; font-size: 0.8rem; color: var(--accent-pink); font-weight: 700;">
              ${formatBaht(item.price)} × ${qty} = ${formatBaht(item.price * qty)}
            </div>
          </div>
          <div style="display: flex; align-items: center; gap: 0.35rem;">
            <button class="qty-btn" onclick="changeItemQty('${id}', -1)">-</button>
            <span style="min-width: 20px; text-align: center; font-weight: 700;">${qty}</span>
            <button class="qty-btn" onclick="changeItemQty('${id}', 1)">+</button>
          </div>
        </div>
      `;
      })
      .join('');
  }

  document.getElementById('sumSubtotal').textContent = formatBaht(subtotal);
  document.getElementById('sumStampDiscount').textContent = stampDiscount > 0 ? `-฿${stampDiscount}` : '฿0';
  document.getElementById('sumLuckyDiscount').textContent =
    luckyDiscount > 0 ? `-฿${luckyDiscount} (${activeCoupon.code})` : '฿0';
  document.getElementById('sumFinalTotal').textContent = formatBaht(finalTotal);
}

